"""Approximate historical shapes for The Rise of Rome (lon, lat). Built from simple hand-drawn outlines plus modern
country outlines (Natural Earth, via places.country_polys) clipped to period frontiers. Borders are APPROXIMATE
(narrative maps, not survey data). Every function returns a list of polygons (lists of (lon, lat))."""
import functools
from shapely.geometry import Polygon, MultiPolygon, Point, box
from shapely.ops import unary_union
import places as PL


def _iso(c, idx=None):
    ps = [Polygon(p) for p in PL.country_polys(c) if len(p) > 2]
    ps = sorted(ps, key=lambda p: -p.area)
    if idx is not None: ps = [ps[i] for i in ([idx] if isinstance(idx, int) else idx)]
    return unary_union([p.buffer(0) for p in ps])


def G(*parts):
    """union of parts: 'ISO:XXX', 'ISO:XXX#0' (n-th largest polygon), coordinate lists, ('circle', (lon, lat), r), shapely geoms"""
    gs = []
    for p in parts:
        if isinstance(p, str):
            c, _, i = p[4:].partition('#'); gs.append(_iso(c, int(i) if i else None))
        elif isinstance(p, tuple) and p and p[0] == 'circle': gs.append(Point(p[1]).buffer(p[2], 32))
        elif hasattr(p, 'geom_type'): gs.append(p)
        else: gs.append(Polygon(p).buffer(0))
    return unary_union(gs)


def polys(g, simp=0.03, min_area=0.02):
    g = g.buffer(0).simplify(simp)
    gs = list(g.geoms) if isinstance(g, MultiPolygon) else [g]
    return [[(round(x, 3), round(y, 3)) for x, y in q.exterior.coords] for q in gs if not q.is_empty and q.area >= min_area]


